char *FD_GitIgnore = "*~\n\\#*\\#\n.\\#*\nbuild/\n.vscode/\n*.code-workspace\n# Generated by 'newcpp', feel free to modify it...\n";
char *FD_MainC = "#include <stdio.h>\n\nint main() {\n    printf(\"Hello World\"\\n);\n}\n";
char *FD_MainCXX = "#include <iostream>\n\nint main() {\n    std::cout << \"Hello World\\n\";\n}\n";

int createProject(ProjectData *data) {
     mode_t mode = 0755;
     printf("\n1) Creating directory of project...\n");
     int pathId = createProjectPath(data->pathdata->path, mode, data->name);
     if (pathId == 0) {
          printf(GREEN "[+] Project dir created!\n -- %s\n" RESET, data->pathdata->path);
     }
     if (data->useCmake == true) {
          printf("\n2) Creating CMake project structure...\n");
          int cmkStatus = CMakeCreateConfig(data);
          if (cmkStatus == 0) {
               printf(GREEN"[+] CMakeLists.txt config created\n"RESET);
          }
          int dir1 = createDir(data->pathdata->path, "build");
          if (dir1 == 0) {
               printf(GREEN"[+] CMake build/ directory created!\n"RESET);
          }
          int dir2 = createDir(data->pathdata->path, "include");
          if (dir2 == 0) {
               printf(GREEN"[+] include/ directory created!\n"RESET);
          }
          int dir3 = createDir(data->pathdata->path, "src");
          if (dir3 == 0) {
               printf(GREEN"[+] src/ directory created!\n"RESET);
          }
     } else {
          printf("\n2) Skipping project structure...\nNo directories created...\n");
       
     }
     printf("\n3) Adding files to project...\n");
     int fileGit = createFile(data->pathdata->path, ".gitignore", FD_GitIgnore);
     if (fileGit == 0) printf(GREEN"[+] .gitignore added!\n"RESET);
     if (data->useCmake == true) {
          char srcPath[1024];
          int fileSt = 0;
          size_t pathSize = sizeof(srcPath);
          strncpy(srcPath, data->pathdata->path, pathSize);
          strncat(srcPath, "/src", pathSize);
          if (data->type == PTYPE_C) {
               fileSt = createFile(srcPath, "main.c", FD_MainC);
               if (fileSt == 0) printf(GREEN"[+] src/main.c created!\n"RESET);
          } else {
               fileSt = createFile(srcPath, "main.cpp", FD_MainCXX);
               if (fileSt == 0) printf(GREEN"[+] src/main.cpp created!\n"RESET);
          }
     } else {
          int fileSt = 0;
          if (data->type == PTYPE_C) {
               fileSt = createFile(data->pathdata->path, "main.c", FD_MainC);
               if (fileSt == 0) printf(GREEN"[+] main.c created!\n"RESET);
          } else {
               fileSt = createFile(data->pathdata->path, "main.cpp", FD_MainCXX);
               if (fileSt == 0) printf(GREEN"[+] main.cpp created!\n"RESET);
          }
     }

     printf(GREEN "\n\nPROJECT '%s' CREATED\n" RESET, data->name);
     printf("\nNavigate --  cd %s", data->pathdata->path);
     if (data->useCmake == true) {
          printf(GREEN"\n\n---- Build with CMake ----\n"RESET);
          printf("\n1)    cd %s/build\n", data->pathdata->path);
          printf("2)    cmake ..\n");
          printf("3)    cmake --build .\n");
          printf("4)    ./%s\n", data->name);
     } else {
          if (data->type == PTYPE_C) {
               printf("\nCompiling --  gcc main.c -o main\n");
          } else {
               printf("\nCompiling --  g++ main.cpp -o main\n");
          }
          printf("Running --  ./main\n");
     }
    
     return 0;
}
